// Realistic (if illustrative) GitHub Actions workflow YAML, stored on
// Workflow.definition so the CI optimizer (src/lib/optimizer/analyze.ts) has
// real text to analyze instead of nothing. These intentionally omit
// dependency caching and use unnecessary `needs:` chains — the exact
// patterns the optimizer looks for — so demo mode shows genuine, non-trivial
// recommendations rather than an empty state.

export const WEB_APP_CI_YAML = `name: CI
on: [push, pull_request]
jobs:
  lint:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 20
      - run: pnpm install
      - run: pnpm lint
  build:
    needs: lint
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 20
      - run: pnpm install
      - run: pnpm build
  test:
    needs: build
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 20
      - run: pnpm install
      - run: pnpm test
`;

